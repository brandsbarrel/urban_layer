// Article, editor pick, aur buying guide teeno ko ek unified shape mein combine karta hai
// taaki article detail page kisi bhi slug ke liye graceful preview dikha sake.
export function getJournalEntryBySlug(slug) {
    const combined = [
        { ...featuredArticle, date: 'Autumn/Winter Edition' },
        ...articles,
        ...editorPicks.map((p) => ({
            ...p,
            badge: p.tag,
            date: '',
            readTime: '',
        })),
        ...buyingGuides.map((g) => ({
            ...g,
            badge: g.label,
            date: '',
            readTime: '',
        })),
    ];
    return combined.find((entry) => entry.slug === slug) || null;
}